export const ICON_SIZE = 20;

// Hat and top icons reuse the paper-doll shapes, so an item looks the same in
// the bag as it does on the hero. hero.js registers them here to avoid a cycle.
export const SHAPE_ICONS = { hat: {} };

export function iconGrid(itemId) {
  const it = ITEMS[itemId];
  let rows, map;
  const main = RAMPS[it.look?.ramp || it.ramp] || RAMPS.steel;
  const trim = RAMPS[it.look?.trim || it.look?.ramp] || main;
  if (it.slot === 'hat' || it.slot === 'top') {
    rows = it.slot === 'top' ? TOP_ICONS[it.look.shape] : SHAPE_ICONS.hat[it.look.shape];
    map = { 7: main[0], 8: main[1], 9: main[2], T: trim[0], U: trim[1], V: trim[2] };
  } else {
    const ic = ICONS[it.icon];
    rows = ic.rows;
    map = ic.map ? ic.map(it.ramp) : { 1: main[0], 2: main[1], 3: main[2], T: trim[0], U: trim[1], V: trim[2] };
  }
  // centre in the icon box
  const w = Math.max(...rows.map((r) => r.length));
  const h = rows.length;
  const x = Math.floor((ICON_SIZE - w) / 2);
  const y = Math.floor((ICON_SIZE - h) / 2);
  return compose(ICON_SIZE, ICON_SIZE, [{ rows, x, y, map }]);
}

export function emptyGrid() {
  return new Grid(ICON_SIZE, ICON_SIZE);
}

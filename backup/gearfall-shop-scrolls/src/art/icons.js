// Item icons. Written as fill-only grids (the outline is added when composed).
// Weapons also carry a `grip`: the pixel the hero's hand closes around, so the
// same art is drawn in the hero's hand.
//
// Keys: 1 2 3 = the item's main ramp, T U V = handle/trim ramp, anything else
// is a literal palette key.

import { compose, Grid } from './pixel.js';
import { RAMPS } from './palette.js';
import { ITEMS } from '../data.js';

const rampKeys = (main, trim) => ({
  1: main[0], 2: main[1], 3: main[2],
  T: trim[0], U: trim[1], V: trim[2],
});

const weapon = (rows, grip, handle = 'leather') => ({
  rows, grip, map: (ramp) => rampKeys(RAMPS[ramp] || RAMPS.steel, RAMPS[handle]),
});

